from reportlab.pdfbase import pdfmetrics

OUT = r"D:\RAG项目\产品说明书"
os.makedirs(OUT, exist_ok=True)
pdfmetrics.registerFont(UnicodeCIDFont("STSong-Light"))

S = {
    "h1": ParagraphStyle("h1", fontName="STSong-Light", fontSize=15, leading=20, spaceAfter=8),
    "h2": ParagraphStyle("h2", fontName="STSong-Light", fontSize=12, leading=17, spaceBefore=7, spaceAfter=4),
    "p": ParagraphStyle("p", fontName="STSong-Light", fontSize=10.5, leading=15.5, spaceAfter=4),
    "note": ParagraphStyle("note", fontName="STSong-Light", fontSize=9.5, leading=14, textColor=colors.HexColor("#8B0000"), spaceAfter=4),
}
FOOT = "虚构演示资料 · 与任何真实产品无关"

def footer(canvas, doc):
    canvas.saveState()
    canvas.setFont("STSong-Light", 8)
    canvas.setFillColor(colors.grey)
    canvas.drawCentredString(A4[0] / 2, 1.1 * cm, f"{FOOT} · 第 {doc.page} 页")
    canvas.restoreState()

def P(t): return Paragraph(t, S["p"])
def H1(t): return Paragraph(t, S["h1"])
def H2(t): return Paragraph(t, S["h2"])
def NOTE(t): return Paragraph("【注意】" + t, S["note"])
def REF(d, pg=None): return f"参见《{d}》{'第'+str(pg)+'页' if pg else ''}。"
def TBL(data):
    t = Table(data)
    t.setStyle(TableStyle([
        ("FONTNAME", (0, 0), (-1, -1), "STSong-Light"),
        ("FONTSIZE", (0, 0), (-1, -1), 9.5),
        ("GRID", (0, 0), (-1, -1), 0.4, colors.grey),
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#E8EEF7")),
        ("TOPPADDING", (0, 0), (-1, -1), 3), ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
    ]))
    return t

def build(filename, flow):
    doc = SimpleDocTemplate(os.path.join(OUT, filename), pagesize=A4,
                            topMargin=1.8 * cm, bottomMargin=1.8 * cm)
    doc.build(flow, onFirstPage=footer, onLaterPages=footer)
    print("OK", filename)

